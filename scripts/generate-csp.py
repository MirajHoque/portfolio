#!/usr/bin/env python3
"""Generate hosting headers, including a Content Security Policy.

The policy allows no inline scripts. Any <script> block that lives inside the
HTML (the JSON-LD block, for example) is allow-listed by its SHA-256 hash, so
editing that block without regenerating the headers is caught by CI instead of
silently breaking in a browser.

    python3 scripts/generate-csp.py          # rewrite the header files
    python3 scripts/generate-csp.py --check  # fail if they are out of date
"""

from __future__ import annotations

import base64
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HTML_FILES = ["index.html", "404.html"]

# Third parties the page is allowed to talk to. Add your form endpoint or
# analytics host here, and nowhere else.
FORM_ENDPOINT = "https://formspree.io"

INLINE_SCRIPT = re.compile(
    r"<script(?![^>]*\ssrc=)[^>]*>(.*?)</script>", re.DOTALL | re.IGNORECASE
)


def inline_hashes() -> list[str]:
    """SHA-256 hashes of every inline script block, in document order."""
    hashes: list[str] = []
    for name in HTML_FILES:
        path = ROOT / name
        if not path.exists():
            continue
        for body in INLINE_SCRIPT.findall(path.read_text(encoding="utf-8")):
            digest = hashlib.sha256(body.encode("utf-8")).digest()
            value = f"'sha256-{base64.b64encode(digest).decode('ascii')}'"
            if value not in hashes:
                hashes.append(value)
    return hashes


def csp() -> str:
    script_src = " ".join(["'self'"] + inline_hashes())
    return "; ".join(
        [
            "default-src 'self'",
            f"script-src {script_src}",
            # Inline styles are used for a handful of layout one-offs on the 404 page.
            "style-src 'self' 'unsafe-inline'",
            "img-src 'self' data:",
            "font-src 'self'",
            f"connect-src 'self' {FORM_ENDPOINT}",
            f"form-action 'self' {FORM_ENDPOINT}",
            "base-uri 'self'",
            "frame-ancestors 'none'",
            "object-src 'none'",
            "upgrade-insecure-requests",
        ]
    )


COMMON_HEADERS = {
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), interest-cohort=()",
    "Strict-Transport-Security": "max-age=63072000; includeSubDomains; preload",
    "Cross-Origin-Opener-Policy": "same-origin",
    "X-Frame-Options": "DENY",
}

BANNER = "# Generated by scripts/generate-csp.py — do not edit by hand.\n"


def render_headers_file() -> str:
    """Netlify and Cloudflare Pages `_headers` format."""
    lines = [BANNER, "/*\n"]
    lines += [f"  {k}: {v}\n" for k, v in COMMON_HEADERS.items()]
    lines.append(f"  Content-Security-Policy: {csp()}\n")
    lines += [
        "\n# Fingerprint-free assets: revalidate quickly, but let the CDN help.\n",
        "/assets/*\n",
        "  Cache-Control: public, max-age=3600, stale-while-revalidate=86400\n",
        "\n/*.html\n",
        "  Cache-Control: public, max-age=0, must-revalidate\n",
    ]
    return "".join(lines)


def render_netlify_toml() -> str:
    headers = dict(COMMON_HEADERS)
    headers["Content-Security-Policy"] = csp()
    body = [BANNER, '\n[build]\n  publish = "."\n\n[[headers]]\n  for = "/*"\n\n  [headers.values]\n']
    body += [f'    {k} = "{v}"\n' for k, v in headers.items()]
    body += [
        '\n[[headers]]\n  for = "/assets/*"\n\n  [headers.values]\n',
        '    Cache-Control = "public, max-age=3600, stale-while-revalidate=86400"\n',
    ]
    return "".join(body)


def render_vercel_json() -> str:
    headers = [{"key": k, "value": v} for k, v in COMMON_HEADERS.items()]
    headers.append({"key": "Content-Security-Policy", "value": csp()})
    config = {
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "cleanUrls": True,
        "trailingSlash": False,
        "headers": [
            {"source": "/(.*)", "headers": headers},
            {
                "source": "/assets/(.*)",
                "headers": [
                    {
                        "key": "Cache-Control",
                        "value": "public, max-age=3600, stale-while-revalidate=86400",
                    }
                ],
            },
        ],
    }
    return json.dumps(config, indent=2) + "\n"


TARGETS = {
    "_headers": render_headers_file,
    "netlify.toml": render_netlify_toml,
    "vercel.json": render_vercel_json,
}


def main() -> int:
    check = "--check" in sys.argv
    stale: list[str] = []

    for name, render in TARGETS.items():
        path = ROOT / name
        content = render()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(name)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {name}")

    if check and stale:
        print("Out of date: " + ", ".join(stale), file=sys.stderr)
        print("Run: python3 scripts/generate-csp.py", file=sys.stderr)
        return 1

    if check:
        print("Headers are up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
